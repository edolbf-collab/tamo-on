import {readFile,writeFile,mkdir,readdir,unlink} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const root=fileURLToPath(new URL('../../marketplace/',import.meta.url));
// Keep the published package, even across repeated local builds before a commit.
let previous=[];
try{previous=JSON.parse(execFileSync('git',['show','HEAD:marketplace/pilot-assets.json'],{cwd:root,encoding:'utf8',stdio:['ignore','pipe','ignore']}));}
catch{try{previous=JSON.parse(await readFile(resolve(root,'pilot-assets.json'),'utf8'));}catch{}}
const sources=JSON.parse(await readFile(resolve(root,'pilot-source-assets.json'),'utf8'));
const blocks=await Promise.all(sources.map(async path=>{
 const name=path.split('?')[0];
 if(name.startsWith('/')||name.includes('..'))throw new Error('Invalid source path');
 return `\n;/* ${name} */\n`+await readFile(resolve(root,name),'utf8');
}));
const content='/* Generated by integration/marketplace/build-assets.mjs. */\n'+blocks.join('\n;\n');
const hash=createHash('sha256').update(content).digest('hex').slice(0,12), name=`pilot-${hash}.js`;
await mkdir(resolve(root,'assets'),{recursive:true});
await writeFile(resolve(root,'assets',name),content);
if(!previous.includes('assets/'+name))for(const old of await readdir(resolve(root,'assets')))if(/^pilot-[a-f0-9]{12}\.js$/.test(old)&&old!==name&&!previous.includes('assets/'+old))await unlink(resolve(root,'assets',old));
await writeFile(resolve(root,'pilot-assets.json'),JSON.stringify(['assets/'+name],null,2)+'\n');
console.log(`Bundle: ${name}; ${sources.length} ordered sources; ${Buffer.byteLength(content)} bytes`);
